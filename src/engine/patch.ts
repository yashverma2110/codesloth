export interface ParsedPatch {
  added: string[];
  removed: string[];
  /** Head-side view reconstructed from context + added lines (may be partial). */
  headView: string;
}

/** Parse a GitHub per-file `patch` string (hunks only, no file headers). */
export function parsePatch(patch: string | undefined): ParsedPatch {
  const added: string[] = [];
  const removed: string[] = [];
  const head: string[] = [];
  if (!patch) return { added, removed, headView: "" };
  for (const line of patch.split("\n")) {
    if (line.startsWith("@@")) {
      head.push("");
      continue;
    }
    if (line.startsWith("\\ No newline")) continue;
    const c = line[0];
    const body = line.slice(1);
    if (c === "+") {
      added.push(body);
      head.push(body);
    } else if (c === "-") {
      removed.push(body);
    } else {
      head.push(body);
    }
  }
  return { added, removed, headView: head.join("\n") };
}

/** For an added file, the patch contains the whole content. */
export function contentFromAddedPatch(patch: string | undefined): string | undefined {
  if (!patch) return undefined;
  return parsePatch(patch).added.join("\n");
}

/**
 * Formatting-only: the multiset of non-whitespace content in removed lines equals that of added lines,
 * and there is at least one change. Detects reindentation, trailing-space, line-wrapping-free reformatting.
 * Also treats a pure reflow (same tokens, different line breaks) as formatting-only by comparing
 * the concatenated whitespace-stripped text.
 */
export function isFormattingOnly(patch: string | undefined): boolean {
  if (!patch) return false;
  const { added, removed } = parsePatch(patch);
  if (added.length === 0 && removed.length === 0) return false;
  const norm = (s: string) => s.replace(/\s+/g, "");
  const a = added.map(norm).filter(Boolean);
  const r = removed.map(norm).filter(Boolean);
  if (a.length === 0 && r.length === 0) return true; // only blank-line changes
  if (a.join("") === r.join("")) return true;
  if (a.length !== r.length) return false;
  const count = new Map<string, number>();
  for (const x of a) count.set(x, (count.get(x) ?? 0) + 1);
  for (const x of r) {
    const n = count.get(x);
    if (!n) return false;
    count.set(x, n - 1);
  }
  return true;
}

/** Look for generated-code markers in the first lines of content. */
export function hasGeneratedMarker(text: string | undefined): string | undefined {
  if (!text) return undefined;
  const head = text.split("\n").slice(0, 15).join("\n");
  if (/^\/\/ Code generated .* DO NOT EDIT\.?$/m.test(head)) return "has Go 'Code generated … DO NOT EDIT' header";
  if (/@generated\b/.test(head)) return "has an @generated marker";
  if (/(auto-?generated|autogenerated) (file|code)|do not edit (this file|manually)/i.test(head))
    return "header says the file is auto-generated";
  return undefined;
}
