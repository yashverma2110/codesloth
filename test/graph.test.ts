import { describe, expect, it } from "vitest";
import { buildGraph, clusterId, GENERATED_NODE, searchNodes } from "../src/graph/build";
import { layoutGraph } from "../src/graph/layout";
import { renderSvg } from "../src/graph/svg";
import type { LayerPlan, LayerFile } from "../src/engine/types";
import { readFileSync } from "node:fs";

const f = (path: string, extra: Partial<LayerFile> = {}): LayerFile => ({ path, status: "modified", additions: 1, deletions: 0, category: "source", reason: "r", ...extra });
const layer = (id: string, index: number, files: LayerFile[]) => ({ id, index, title: id, label: id, description: "", files, stats: { files: files.length, additions: files.length, deletions: 0 } });

const plan: LayerPlan = {
  version: 1,
  engineVersion: "t",
  warnings: [],
  stats: { files: 7, additions: 7, deletions: 0, edges: 3, contentsUsed: 0 },
  layers: [
    layer("contract", 0, [f("api/types.ts", { category: "contract" })]),
    layer("core", 1, [f("src/a.ts"), f("src/b.ts")]),
    layer("caller1", 2, [f("src/ui/z.ts"), f("src/ui/y.ts")]),
    layer("test", 3, [f("src/a.test.ts", { category: "test" })]),
    layer("generated", 4, [f("package-lock.json", { category: "generated" }), f("pnpm-lock.yaml", { category: "generated" })]),
  ],
  edges: [
    { from: "src/a.ts", to: "api/types.ts", kind: "import" },
    { from: "src/ui/z.ts", to: "src/b.ts", kind: "import" },
    { from: "src/ui/y.ts", to: "src/a.ts", kind: "import" },
    { from: "src/a.test.ts", to: "src/a.ts", kind: "test" },
  ],
};

describe("buildGraph", () => {
  it("makes one node per file, keeps import and test edges, collapses generated by default", () => {
    const g = buildGraph(plan);
    expect(g.nodes.map((n) => n.id)).toEqual(["api/types.ts", "src/a.ts", "src/b.ts", "src/ui/z.ts", "src/ui/y.ts", "src/a.test.ts", GENERATED_NODE]);
    const gen = g.nodes.find((n) => n.id === GENERATED_NODE)!;
    expect(gen.kind).toBe("generated");
    expect(gen.paths).toEqual(["package-lock.json", "pnpm-lock.yaml"]);
    expect(g.edges.filter((e) => e.kind === "test")).toEqual([{ from: "src/a.test.ts", to: "src/a.ts", kind: "test", count: 1 }]);
    expect(g.edges.filter((e) => e.kind === "import")).toHaveLength(3);
    expect(g.neighbors.get("src/a.ts")).toEqual(new Set(["api/types.ts", "src/ui/y.ts", "src/a.test.ts"]));
  });

  it("expands generated files on request and hides filtered layers (dropping their edges)", () => {
    const g = buildGraph(plan, { expanded: new Set([GENERATED_NODE]), hiddenLayers: new Set(["contract"]) });
    expect(g.nodes.some((n) => n.id === "package-lock.json")).toBe(true);
    expect(g.nodes.some((n) => n.id === "api/types.ts")).toBe(false);
    expect(g.edges.some((e) => e.to === "api/types.ts")).toBe(false);
    expect(g.layers.find((l) => l.id === "contract")!.hidden).toBe(true);
  });

  it("marks reviewed layers and changed files", () => {
    const g = buildGraph(plan, { reviewedLayers: new Set(["core"]), changedPaths: new Set(["src/b.ts"]) });
    expect(g.nodes.find((n) => n.id === "src/a.ts")!.reviewed).toBe(true);
    expect(g.nodes.find((n) => n.id === "src/b.ts")!.changed).toBe(true);
    expect(g.nodes.find((n) => n.id === "src/ui/z.ts")!.reviewed).toBe(false);
  });

  it("clusters large PRs by directory, aggregates edges, and expands a cluster on demand", () => {
    const many = Array.from({ length: 30 }, (_, i) => f(`pkg/m${i % 3}/f${i}.ts`));
    const big: LayerPlan = { ...plan, layers: [layer("core", 0, many), layer("caller1", 1, [f("app/main.ts")])], edges: many.map((m) => ({ from: "app/main.ts", to: m.path, kind: "import" as const })) };
    const g = buildGraph(big, { maxNodes: 10 });
    expect(g.nodes.filter((n) => n.kind === "cluster")).toHaveLength(3);
    expect(g.clusteredFiles).toBe(30);
    const e = g.edges.find((x) => x.to === clusterId("core", "pkg/m0"))!;
    expect(e.count).toBe(10);
    const g2 = buildGraph(big, { maxNodes: 10, expanded: new Set([clusterId("core", "pkg/m0")]) });
    expect(g2.nodes.filter((n) => n.kind === "file" && n.layerId === "core")).toHaveLength(10);
  });

  it("search matches file names and full paths", () => {
    const g = buildGraph(plan);
    expect(searchNodes(g, "UI/")).toEqual(new Set(["src/ui/z.ts", "src/ui/y.ts"]));
    expect(searchNodes(g, "lock")).toEqual(new Set([GENERATED_NODE]));
    expect(searchNodes(g, "  ")).toEqual(new Set());
  });
});

describe("layoutGraph", () => {
  it("stacks layers top-to-bottom in review order (contracts at the top)", () => {
    const g = buildGraph(plan);
    const L = layoutGraph(g);
    const ys = L.bands.map((b) => b.y);
    expect(L.bands.map((b) => b.layerId)).toEqual(["contract", "core", "caller1", "test", "generated"]);
    expect([...ys].sort((a, b) => a - b)).toEqual(ys);
    expect(L.pos.get("api/types.ts")!.y).toBeLessThan(L.pos.get("src/a.ts")!.y);
    expect(L.pos.get("src/a.ts")!.y).toBeLessThan(L.pos.get("src/ui/y.ts")!.y);
  });

  it("orders nodes by the barycenter of placed neighbours to reduce crossings", () => {
    const g = buildGraph(plan);
    const L = layoutGraph(g);
    // y imports a (left in core), z imports b (right) -> y should sit left of z even though "z" < "y" is false alphabetically
    expect(L.pos.get("src/a.ts")!.x).toBeLessThan(L.pos.get("src/b.ts")!.x);
    expect(L.pos.get("src/ui/y.ts")!.x).toBeLessThan(L.pos.get("src/ui/z.ts")!.x);
  });

  it("wraps wide layers into rows and keeps Go packages contiguous with a group box", () => {
    const files = [f("x/a.go", { group: "pkg:x" }), f("y/q.go"), f("x/b.go", { group: "pkg:x" }), f("x/c.go", { group: "pkg:x" }), f("z/r.go")];
    const p: LayerPlan = { ...plan, layers: [layer("core", 0, files)], edges: [] };
    const L = layoutGraph(buildGraph(p), { maxPerRow: 3 });
    const xs = ["x/a.go", "x/b.go", "x/c.go"].map((id) => L.pos.get(id)!);
    expect(new Set(xs.map((q) => q.y)).size).toBe(1);
    expect(L.groups).toHaveLength(1);
    expect(L.groups[0].label).toBe("package x");
    expect(L.pos.get("y/q.go")!.y).not.toBe(xs[0].y); // y, z fill row 1; the package moves to its own row
  });

  it("renders a self-contained SVG with escaped labels for a real sample plan", () => {
    const demo = JSON.parse(readFileSync("src/demo/demo-plan.json", "utf8"));
    const g = buildGraph(demo.plan);
    const svg = renderSvg(g, layoutGraph(g), { standalone: true });
    expect(svg.startsWith("<svg")).toBe(true);
    expect(svg).toContain('class="g-edge test"');
    expect((svg.match(/class="g-node /g) ?? []).length).toBe(g.nodes.length);
    const evil = buildGraph({ ...plan, layers: [layer("core", 0, [f('a/<img src=x onerror="1">.ts')])], edges: [] });
    expect(renderSvg(evil, layoutGraph(evil))).not.toContain("<img");
  });
});
