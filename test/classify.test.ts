import { describe, expect, it } from "vitest";
import { classifyFile, detectLang } from "../src/engine/classify";
import { parseGitAttributes } from "../src/engine/glob";
import type { PRFile } from "../src/engine/types";

const f = (filename: string, extra: Partial<PRFile> = {}): PRFile => ({ filename, status: "modified", additions: 3, deletions: 1, changes: 4, sha: "x", patch: "@@ -1 +1 @@\n-a\n+b", ...extra });
const cat = (p: string, extra?: Partial<PRFile>) => classifyFile(f(p, extra)).category;

describe("classifier", () => {
  it.each([
    "package-lock.json", "web/yarn.lock", "pnpm-lock.yaml", "go.sum", "poetry.lock", "uv.lock",
    "public/app.min.js", "dist/index.js", "vendor/github.com/x/y.go", "api/v1/user.pb.go", "gen/user_pb2.py",
    "src/__generated__/graphql.ts", "src/__snapshots__/a.test.ts.snap",
  ])("generated: %s", (p) => expect(cat(p)).toBe("generated"));

  it.each([
    "src/a.test.ts", "src/a.spec.tsx", "src/__tests__/a.ts", "pkg/store/store_test.go", "tests/test_user.py",
    "app/user_test.py", "conftest.py", "e2e/login.cy.ts", "test/fixtures/x.json", "src/components/Button.spec.vue",
  ])("test: %s", (p) => expect(cat(p)).toBe("test"));

  it.each([
    "proto/user.proto", "schema.graphql", "api/openapi.yaml", "db/migrations/20240101_add_users.sql",
    "migrations/0003_auto.py", "models/migrations/v1_22/v283.go", "src/types/user.ts", "src/global.d.ts",
    "src/user.types.ts", "app/schemas/user.py",
  ])("contract: %s", (p) => expect(cat(p)).toBe("contract"));

  it("does not treat a feature package named 'migrations' as DB migrations", () => {
    expect(cat("services/migrations/github.go")).toBe("source");
  });

  it.each([
    "package.json", "go.mod", "pyproject.toml", "requirements-dev.txt", ".github/workflows/ci.yml", "Dockerfile",
    "tsconfig.json", "vite.config.ts", ".eslintrc.cjs", "deploy/values.yaml", "locales/en.json", "Makefile",
  ])("config: %s", (p) => expect(cat(p)).toBe("config"));

  it.each(["README.md", "docs/guide/intro.md", "LICENSE", "deploy/README.md", "assets/logo.png"])("docs/assets: %s", (p) => expect(cat(p)).toBe("docs"));

  it.each(["src/app.ts", "src/components/Button.tsx", "web/src/views/Home.vue", "cmd/server/main.go", "app/services/user.py", "lib/index.mjs"])(
    "source: %s",
    (p) => expect(cat(p)).toBe("source"),
  );

  it("detects rename-only", () => {
    const c = classifyFile(f("src/new.ts", { status: "renamed", previous_filename: "src/old.ts", changes: 0, additions: 0, deletions: 0, patch: undefined }));
    expect(c).toMatchObject({ category: "mechanical", kind: "rename-only" });
    expect(c.reason).toContain("src/old.ts");
  });

  it("detects formatting-only (re-indent) changes", () => {
    const patch = "@@ -1,3 +1,3 @@\n-function a() {\n-return 1;\n-}\n+function a() {\n+  return 1;\n+}";
    expect(classifyFile(f("src/a.ts", { patch }))).toMatchObject({ category: "mechanical", kind: "formatting-only" });
  });

  it("does not flag real changes as formatting-only", () => {
    const patch = "@@ -1 +1 @@\n-return 1;\n+return 2;";
    expect(cat("src/a.ts", { patch })).toBe("source");
  });

  it("honours .gitattributes linguist-generated (and later negation)", () => {
    const rules = parseGitAttributes("web/src/api/** linguist-generated=true\n*.gen.yaml linguist-generated\nweb/src/api/handwritten.ts -linguist-generated\n");
    expect(classifyFile(f("web/src/api/client.ts"), { gitattributes: rules })).toMatchObject({ category: "generated", kind: "linguist-generated" });
    expect(classifyFile(f("x/y/z.gen.yaml"), { gitattributes: rules }).category).toBe("generated");
    expect(classifyFile(f("web/src/api/handwritten.ts"), { gitattributes: rules }).category).toBe("source");
  });

  it("detects generated-code header markers", () => {
    expect(classifyFile(f("internal/x/zz.go"), { content: "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x" }).category).toBe("generated");
    expect(classifyFile(f("src/x.ts"), { content: "/* @generated */\nexport {}" }).category).toBe("generated");
  });

  it("detects languages", () => {
    expect(["a.ts", "a.jsx", "a.mjs", "a.vue", "a.go", "a.py", "a.rb"].map(detectLang)).toEqual(["js", "js", "js", "vue", "go", "python", "other"]);
  });
});

describe("classifier regressions from real PRs", () => {
  it("code under a charts/ or deploy/ folder is source, YAML there is config", () => {
    expect(cat("packages/excalidraw/charts/charts.bar.ts")).toBe("source");
    expect(cat("deploy/app/values.yaml")).toBe("config");
  });
});
